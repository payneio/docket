src_wrapper_echo() { cat <<'EOF_src_wrapper_echo'
#!/usr/bin/env bash
# A wrapper that runs no assistant at all.
#
# For exercising the runner: the contract is a subprocess and a JSON shape, so
# the whole loop can be driven without a model, an API key, or a minute of
# waiting. Set HARNESS_ECHO_OUTCOME to whichever branch you want to see.
#
# It is also the shortest possible answer to "what does a wrapper have to do".
set -uo pipefail
REQ="$(cat)"
echo "echo wrapper saw: $(printf '%s' "$REQ" | jq -c '{entry: .entry.id, state: .entry.state, ws: .workspace}')" >&2
printf '%s' "$REQ" | jq -r '.workspace' | xargs -I{} mkdir -p {}/.harness/echo

case "${HARNESS_ECHO_OUTCOME:-progressed}" in
  blocked) jq -nc '{outcome:"blocked", note:"needs a decision",
                   question:"Which of the two approaches did you want?"}' ;;
  declined) jq -nc '{outcome:"declined", note:"outside what I am set up to do"}' ;;
  delivered) jq -nc '{outcome:"delivered", note:"done"}' ;;
  failed) exit 3 ;;
  *) jq -nc '{outcome:"progressed", note:"had a look, nothing finished"}' ;;
esac
EOF_src_wrapper_echo
}

src_wrapper_opencode() { cat <<'EOF_src_wrapper_opencode'
#!/usr/bin/env bash
# opencode.
#
# Continuation: **captured, but scoped by directory.** `run -s <id>` continues a
# named session and `--continue` takes the last one; `--dir` decides which
# project that is. Since every subject already has its own workspace, `--dir`
# plus `--continue` is enough on its own -- the last session in this directory is
# by construction the last session about this subject.
#
# The id is still recorded when the output offers one, because `--continue` is a
# statement about recency and an explicit id is a statement about identity, and
# the second survives somebody else running opencode in the same directory.
set -uo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/lib.sh"

REQ="$(cat)"
WS="$(printf '%s' "$REQ" | jq -r '.workspace')"
STATE="$WS/.harness/opencode"; mkdir -p "$STATE"
SESSION_FILE="$STATE/session"

ARGS=(run --dir "$WS" --format json)
[ -n "${OPENCODE_MODEL:-}" ] && ARGS+=(--model "$OPENCODE_MODEL")
[ -n "${OPENCODE_AGENT:-}" ] && ARGS+=(--agent "$OPENCODE_AGENT")
if [ -s "$SESSION_FILE" ]; then
  ARGS+=(--session "$(cat "$SESSION_FILE")")
elif [ -d "$WS/.opencode" ]; then
  ARGS+=(--continue)
fi

# stdout only. The tools separate their streams and this used to merge them with
# `2>&1`, so a diagnostic line landed in the middle of the data: pi prints
# "Warning: No project session found ... creating a new session" on the first run
# of a session, which made the whole JSONL stream unparseable and sent a slice of
# the prompt to the register as the agent's report. Stderr is left to flow to the
# wrapper's own stderr, which the runner already keeps in the run log.
OUT="$(opencode "${ARGS[@]}" "$(default_prompt "$REQ")")"; RC=$?
if [ $RC -ne 0 ] && [ -s "$SESSION_FILE" ]; then
  echo "continuing failed ($RC); starting fresh" >&2
  rm -f "$SESSION_FILE"
  OUT="$(opencode run --dir "$WS" --format json "$(default_prompt "$REQ")")"; RC=$?
fi
printf '%s\n' "$OUT" >&2
debug_dump "$WS" "stdout" "$OUT"

SID="$(printf '%s' "$OUT" | jq -rs '[.[]? | (.sessionID? // .session_id? // .id? // empty)] | first // empty' 2>/dev/null)"
[ -n "$SID" ] && printf '%s' "$SID" > "$SESSION_FILE"

[ $RC -ne 0 ] && { failed_result "opencode exited $RC"; exit 0; }

# JSONL of events. The reply is every `text` event's part, in order -- one
# assistant turn can be split across several. The first version took whatever
# `.text` or `.content` it found last, which was usually a `tool_use` event, so
# the register was posted the arguments of a file write as the agent's report.
REPLY="$(printf '%s' "$OUT" | jq -rs '[.[] | select(.type=="text") | .part.text? // empty] | join("")' 2>/dev/null)"
[ -z "$REPLY" ] && REPLY="$(printf '%s' "$OUT" | tail -c 2000 | tr -d '\000')"
SUMMARY="$(printf '%s' "$REPLY" | head -c 400 | tr '\n' ' ')"

# Three channels, best first. The tool is validated and can refuse a bad call;
# the response is the one every assistant has; the prose heuristic is a last
# resort and may only be wrong towards `progressed`, which leaves the work ours
# and the register honest that nothing moved.
if DECLARED="$(declared_outcome "$WS")"; then
  printf '%s' "$DECLARED" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi
if SAID="$(response_outcome "$REPLY")"; then
  printf '%s' "$SAID" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi
jq -nc --arg n "${SUMMARY:-ran and said nothing}" '{outcome:"progressed", note:$n}'
EOF_src_wrapper_opencode
}

src_wrapper_pi() { cat <<'EOF_src_wrapper_pi'
#!/usr/bin/env bash
# pi.
#
# Continuation: **derived, not stored.** `--session-id <id>` uses that exact
# session and creates it if it is missing, so the id can be computed from the
# subject and there is nothing to keep, nothing to lose, and nothing to go stale.
# The first run and the tenth are the same command.
#
# This is why the contract lets a wrapper store nothing: making every wrapper
# hand an opaque blob back to the runner would have invented state that pi does
# not need.
set -uo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/lib.sh"

REQ="$(cat)"
WS="$(printf '%s' "$REQ" | jq -r '.workspace')"
SUBJECT="$(printf '%s' "$REQ" | jq -r '.entry.subject')"
mkdir -p "$WS/.harness/pi"

# Stable for a subject, and a valid session id wherever it is run. Same input,
# same session, forever.
SESSION_ID="$(printf '%s' "$SUBJECT" | sha256sum | cut -c1-32 \
              | sed -E 's/(.{8})(.{4})(.{4})(.{4})(.{12})/\1-\2-\3-\4-\5/')"

ARGS=(--print --mode json --session-id "$SESSION_ID" --session-dir "$WS/.harness/pi")
[ -n "${PI_PROVIDER:-}" ] && ARGS+=(--provider "$PI_PROVIDER")
[ -n "${PI_MODEL:-}" ] && ARGS+=(--model "$PI_MODEL")

cd "$WS" || { failed_result "cannot enter $WS"; exit 0; }
# stdout only. The tools separate their streams and this used to merge them with
# `2>&1`, so a diagnostic line landed in the middle of the data: pi prints
# "Warning: No project session found ... creating a new session" on the first run
# of a session, which made the whole JSONL stream unparseable and sent a slice of
# the prompt to the register as the agent's report. Stderr is left to flow to the
# wrapper's own stderr, which the runner already keeps in the run log.
OUT="$(pi "${ARGS[@]}" "$(default_prompt "$REQ")")"; RC=$?
printf '%s\n' "$OUT" >&2
debug_dump "$WS" "stdout" "$OUT"

[ $RC -ne 0 ] && { failed_result "pi exited $RC"; exit 0; }

# `--mode json` shape is not guaranteed across versions, so take the first thing
# that looks like a summary and fall back to the raw tail rather than reporting
# nothing.
# JSONL of events. The reply is the text of the last assistant `message_end`,
# and `agent_end.messages` carries the same thing if the stream was cut short.
#
# The first version reached for any `.text` or `.content` it could find, which
# matched the *prompt echoed back in the user message* -- so the register was
# posted a slice of its own instructions as the agent's report.
REPLY="$(printf '%s' "$OUT" | jq -rs '
  ([.[] | select(.type=="message_end") | .message | select(.role=="assistant")] | last)
  // ([.[] | select(.type=="agent_end") | .messages[]? | select(.role=="assistant")] | last)
  | [.content[]? | select(.type=="text") | .text] | join("")' 2>/dev/null)"
[ -z "$REPLY" ] || [ "$REPLY" = "null" ] && REPLY="$(printf '%s' "$OUT" | tail -c 2000 | tr -d '\000')"
SUMMARY="$(printf '%s' "$REPLY" | head -c 400 | tr '\n' ' ')"

# Three channels, best first. The tool is validated and can refuse a bad call;
# the response is the one every assistant has; the prose heuristic is a last
# resort and may only be wrong towards `progressed`, which leaves the work ours
# and the register honest that nothing moved.
if DECLARED="$(declared_outcome "$WS")"; then
  printf '%s' "$DECLARED" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi
if SAID="$(response_outcome "$REPLY")"; then
  printf '%s' "$SAID" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi
jq -nc --arg n "${SUMMARY:-ran and said nothing}" '{outcome:"progressed", note:$n}'
EOF_src_wrapper_pi
}


# Aliases, because the assistants are known by more than one name and being told
# "unknown harness: claude-code" when you asked for the thing you have installed
# is a poor welcome.
# A wrapper is an executable implementing the contract in harness/README.md, so
# "installing a new one" is bundling a file rather than resolving a package. A
# path or a URL is therefore as good as a name, and anybody can ship a wrapper
# for an assistant nobody here has heard of without touching this repository.
CUSTOM=""
case "$HARNESS" in
  http://*|https://*)
    CUSTOM="$(curl -fsSL "$HARNESS")" || die "could not fetch $HARNESS"
    : "${NAME:=docket-$(basename "${HARNESS%%\?*}")}" ;;
  ./*|/*|../*)
    [ -r "$HARNESS" ] || die "no wrapper at $HARNESS"
    CUSTOM="$(cat "$HARNESS")"
    : "${NAME:=docket-$(basename "$HARNESS")}" ;;
esac
if [ -n "$CUSTOM" ]; then
  printf '%s' "$CUSTOM" | head -1 | grep -q '^#!' \
    || die "that does not look like a wrapper: no #! on the first line"
fi

# Shell function names cannot hold a hyphen, so the embedded wrappers are named
# without one and the names people actually type are mapped here. Being told
# "unknown harness: amplifier-agent" when that is exactly what you have would be
# a poor welcome.
case "$HARNESS" in
  claude-coder|claudecoder|coder)    HARNESS=claudecoder ;;
  claude|claude-code|claudecode)     HARNESS=claude ;;
  pi)                                HARNESS=pi ;;
  opencode|open-code)                HARNESS=opencode ;;
  amplifier-agent|amplifieragent)    HARNESS=amplifieragent ;;
  amplifier|amplifier-cli)           HARNESS=amplifier ;;
esac

# What to call each on the way out. `amplifieragent` is an implementation
# detail of bash and should not be the name anybody reads.
display_name() {
  case "$1" in
    amplifieragent) echo amplifier-agent ;;
    claudecoder)    echo claude-coder ;;
    claude)         echo claude-code ;;
    *)              echo "$1" ;;
  esac
}
AVAILABLE="$(for f in $(declare -F | sed -n 's/^declare -f src_wrapper_//p' | sort); do display_name "$f"; done | tr '\n' ' ')"
if [ -n "${LIST:-}" ]; then
  printf 'harnesses: %s\n' "$AVAILABLE"; exit 0
fi
[ -n "$HARNESS" ] || die "which assistant? --harness <${AVAILABLE// /|}>, or a path or URL"
if [ -z "$CUSTOM" ]; then
  declare -F "src_wrapper_$HARNESS" >/dev/null \
    || die "no harness '$HARNESS'; have: $AVAILABLE (or pass a path or URL)"
  command -v "$(display_name "$HARNESS")" >/dev/null 2>&1 \
    || command -v "$HARNESS" >/dev/null 2>&1 \
    || printf 'install: note — %s is not on PATH yet; the runner will need it\n' \
       "$(display_name "$HARNESS")" >&2
fi

: "${NAME:=docket-$(display_name "$HARNESS")}"
mkdir -p "$DEST" || die "cannot create $DEST"
OUT="$DEST/$NAME"

# The bundle. `. lib.sh` lines go, because the library is already above them;
# everything else is verbatim, so what runs here is what was tested there.
strip_source() { grep -v '^\. "\$(cd .*lib\.sh"$' | grep -v '^# shellcheck source=harness/lib.sh$' | grep -v '^\. "\$HERE/lib\.sh"$'; }

{
  printf '#!/usr/bin/env bash\n'
  printf '# docket runner for %s. Generated by install.sh; edit nothing here.\n' "$HARNESS"
  printf '#\n'
  printf '#   DOCKET_URL=https://docket.example DOCKET_API_KEY=dk_… %s\n' "$NAME"
  printf '#\n'
  printf '# DOCKET_API_KEY may be a credential (dk_) or a single-use ticket (dke_),\n'
  printf '# which is spent once and replaced by the credential it buys.\n'
  printf 'set -uo pipefail\n\n'

  printf 'HARNESS_AGENTS_MD_INLINE=1\n'
  printf 'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"\n\n'

  printf '# ---- library ----\n'; src_lib | strip_source

  printf '\n# ---- the instructions handed to the assistant ----\n'
  printf 'write_agents_md() {\n  cat > "$1" <<'"'"'EOF_AGENTS'"'"'\n'
  src_agents
  printf 'EOF_AGENTS\n}\n'

  printf '\n# ---- the outcome tool, offered over MCP where the assistant speaks it ----\n'
  printf 'write_outcome_tool() {\n  cat > "$1" <<'"'"'EOF_TOOL'"'"'\n'
  src_tool
  printf 'EOF_TOOL\n}\n'

  printf '\n# ---- wrapper: %s ----\n' "${CUSTOM:+custom }$(display_name "$HARNESS")"
  # Not indented. It would read better inside the braces and a wrapper is
  # allowed to contain a heredoc, whose terminator must start at column zero --
  # indenting the body silently turns `BRIEF` into `  BRIEF` and the whole file
  # stops parsing at the end.
  printf 'wrapper_main() {\n'
  if [ -n "$CUSTOM" ]; then
    printf '%s' "$CUSTOM" | strip_source
  else
    "src_wrapper_$HARNESS" | strip_source
  fi
  printf '\n}\n'
  printf 'if [ "${HARNESS_ROLE:-}" = "wrapper" ]; then wrapper_main; exit $?; fi\n'

  printf '\n# ---- runner ----\n'
  printf 'HARNESS_WRAPPER="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/%s"\n' "$NAME"
  printf 'export HARNESS_WRAPPER\n'
  src_runner | strip_source
} > "$OUT"
chmod +x "$OUT"

printf 'installed %s\n' "$OUT"

# Arming: the loop a fleetix principal runs. fleetix writes ~/agent once, as a
# stub that exits 78 until something replaces it, and leaves replacing it to an
# installer -- this one. Its contract (fleetix docs/contract.md) is the whole
# interface: the path, mode 0700, the `# fleetix:unarmed` marker, a restart.
if [ -n "$ARM" ]; then
  AGENT="$HOME/agent"
  if [ -e "$AGENT" ] && [ "$(sed -n 2p "$AGENT")" != "# fleetix:unarmed" ]; then
    # A hand-written agent is somebody's decision; never replace one silently.
    [ -n "$FORCE" ] || die "$AGENT is not fleetix's unarmed stub; --force replaces it (kept as $AGENT.bak)"
    cp -p "$AGENT" "$AGENT.bak"
    printf 'kept the previous agent as %s\n' "$AGENT.bak"
  fi
  src_agent_loop | sed "s|@RUNNER@|$OUT|" > "$AGENT.new" && chmod 0700 "$AGENT.new" \
    && mv -f "$AGENT.new" "$AGENT" || die "could not write $AGENT"
  printf 'armed %s -> %s\n' "$AGENT" "$NAME"

  ENVFILE="$HOME/.config/agent/env"
  if [ ! -e "$ENVFILE" ]; then
    mkdir -p "$(dirname "$ENVFILE")" && (umask 077; src_agent_env > "$ENVFILE") \
      || die "could not write $ENVFILE"
    printf 'settings in %s\n' "$ENVFILE"
  fi

  # Only where fleetix put a unit. Anywhere else there is nothing to restart,
  # and `systemctl --user` would be talking to somebody else's manager.
  if [ -f "$HOME/.config/systemd/user/fleet-agent.service" ]; then
    export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"
    if systemctl --user restart fleet-agent; then
      printf 'restarted fleet-agent\n'
    else
      printf 'install: could not restart fleet-agent; it will pick this up on its next start\n' >&2
    fi
  fi
  exit 0
fi
case ":$PATH:" in
  *":$DEST:"*) ;;
  *) printf 'note: %s is not on your PATH\n' "$DEST" >&2 ;;
esac
printf '\nnext:\n  export DOCKET_URL=https://docket.example\n'
printf '  export DOCKET_API_KEY=dke_…      # a ticket from /board/access\n'
printf '  %s\n' "$NAME"
