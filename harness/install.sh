src_wrapper_amplifier() { cat <<'EOF_src_wrapper_amplifier'
#!/usr/bin/env bash
# The `amplifier` CLI -- the modular platform, not `amplifier-agent` beside it.
# They are different programs with different contracts; both are here because
# either may be the thing you have.
#
# Continuation: **captured, and the fallback is implicit.** `run --resume <id>`
# takes an explicit session; `amplifier continue` resumes "the most recent"
# one, which is a fact about the process's own state rather than about this
# subject. The workspace makes the implicit form survivable -- most recent
# *here* is most recent about this -- but the explicit id is preferred whenever
# the run gives one, because "most recent" stops being true the moment anything
# else runs.
#
# Amplifier also carries its own bundles and agents, so the assistant may have a
# task source of its own. That is fine and is the reason this file exists: the
# runner does not need to know, and only this wrapper does.
set -uo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/lib.sh"

REQ="$(cat)"
WS="$(printf '%s' "$REQ" | jq -r '.workspace')"
STATE="$WS/.harness/amplifier"; mkdir -p "$STATE"
SESSION_FILE="$STATE/session"

ARGS=(run --output-format json --mode "${AMPLIFIER_MODE:-single}")
[ -n "${AMPLIFIER_BUNDLE:-}" ] && ARGS+=(--bundle "$AMPLIFIER_BUNDLE")
[ -n "${AMPLIFIER_PROVIDER:-}" ] && ARGS+=(--provider "$AMPLIFIER_PROVIDER")
[ -n "${AMPLIFIER_MODEL:-}" ] && ARGS+=(--model "$AMPLIFIER_MODEL")
[ -s "$SESSION_FILE" ] && ARGS+=(--resume "$(cat "$SESSION_FILE")")

cd "$WS" || { failed_result "cannot enter $WS"; exit 0; }
# stdout only. The tools separate their streams and this used to merge them with
# `2>&1`, so a diagnostic line landed in the middle of the data: pi prints
# "Warning: No project session found ... creating a new session" on the first run
# of a session, which made the whole JSONL stream unparseable and sent a slice of
# the prompt to the register as the agent's report. Stderr is left to flow to the
# wrapper's own stderr, which the runner already keeps in the run log.
OUT="$(amplifier "${ARGS[@]}" "$(default_prompt "$REQ")")"; RC=$?
if [ $RC -ne 0 ] && [ -s "$SESSION_FILE" ]; then
  echo "resume failed ($RC); starting fresh" >&2
  rm -f "$SESSION_FILE"
  OUT="$(amplifier run --output-format json --mode "${AMPLIFIER_MODE:-single}" \
         "$(default_prompt "$REQ")")"; RC=$?
fi
printf '%s\n' "$OUT" >&2
debug_dump "$WS" "stdout" "$OUT"

SID="$(printf '%s' "$OUT" | sed -n '/^[[:space:]]*{/,$p' | jq -r '.session_id // .session // empty' 2>/dev/null)"
[ -n "$SID" ] && printf '%s' "$SID" > "$SESSION_FILE"

[ $RC -ne 0 ] && { failed_result "amplifier exited $RC"; exit 0; }

# Stdout opens with a banner -- "Bundle '...' prepared successfully" -- and the
# JSON follows it, pretty-printed. So the envelope starts at the first line that
# begins a JSON object, and anything before it is noise this wrapper is here to
# absorb. Reading from byte zero got the banner and a parse error, and the raw
# tail that came of it was posted to the register as the agent's report.
ENVELOPE="$(printf '%s' "$OUT" | sed -n '/^[[:space:]]*{/,$p')"
REPLY="$(printf '%s' "$ENVELOPE" | jq -r '.response // .result // .content // empty' 2>/dev/null)"
STATUS="$(printf '%s' "$ENVELOPE" | jq -r '.status // empty' 2>/dev/null)"
if [ -n "$STATUS" ] && [ "$STATUS" != "success" ]; then
  failed_result "amplifier reported $STATUS: $(printf '%s' "$ENVELOPE" | jq -r '.error // empty' | head -c 200)"
  exit 0
fi
[ -z "$REPLY" ] && REPLY="$(printf '%s' "$OUT" | tail -c 2000 | tr -d '\000')"
SUMMARY="$(printf '%s' "$REPLY" | head -c 400 | tr '\n' ' ')"

# Three channels, best first. The tool is validated and can refuse a bad call;
# the response is the one every assistant has; the prose heuristic is a last
# resort and may only be wrong towards `progressed`, which leaves the work ours
# and the register honest that nothing moved.
if DECLARED="$(declared_outcome "$WS")"; then
  printf '%s' "$DECLARED" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi
if SAID="$(response_outcome "$REPLY")"; then
  printf '%s' "$SAID" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi
jq -nc --arg n "${SUMMARY:-ran and said nothing}" '{outcome:"progressed", note:$n}'
EOF_src_wrapper_amplifier
}

src_wrapper_amplifieragent() { cat <<'EOF_src_wrapper_amplifieragent'
#!/usr/bin/env bash
# amplifier-agent — the engine, not the `amplifier` CLI beside it. They are
# different programs; this is the one built to be driven.
#
# Configured with AMPLIFIER_AGENT_PROVIDER / _MODEL / _MODE, deliberately not
# the AMPLIFIER_* names the `amplifier` CLI wrapper uses: they are different
# programs with different provider modules, and a box that runs both would
# otherwise have one variable meaning two things.
#
# Continuation: **caller-chosen id plus an explicit resume**, which is the best
# arrangement of the four here. `--session-id` is ours to pick, so it is derived
# from the subject and never stored; `--resume` says whether to continue the
# transcript, so a first run and a tenth differ by one flag and no bookkeeping
# beyond "have we been here".
#
# Its own docs describe this host exactly: "a subprocess host typically writes
# one file per agent instance and passes --config <path> on every turn". So the
# config, the MCP server and the skills all live in the workspace, which means
# an agent's whole configuration moves with its work and nothing is left behind
# on a machine when the work goes elsewhere.
set -uo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/lib.sh"

REQ="$(cat)"
WS="$(printf '%s' "$REQ" | jq -r '.workspace')"
SUBJECT="$(printf '%s' "$REQ" | jq -r '.entry.subject')"
STATE="$WS/.harness/amplifier-agent"; mkdir -p "$STATE"

SESSION_ID="docket-$(printf '%s' "$SUBJECT" | sha256sum | cut -c1-24)"

# The outcome tool, over MCP. The engine takes a path to an MCP file rather than
# inline JSON, so it is written beside the config it is named in.
CONFIG="$STATE/host-config.json"
MCP_FILE="$STATE/mcp.json"
TOOL="$(install_outcome_tool "$WS" || true)"
if [ -n "$TOOL" ]; then
  jq -nc --arg c "$(command -v python3)" --arg a "$TOOL" --arg ws "$WS" \
    '{mcpServers:{harness:{command:$c, args:[$a], env:{HARNESS_WORKSPACE:$ws}}}}' > "$MCP_FILE"
fi

# The top level of this file is closed -- an unknown key is an error rather than
# a warning -- so it is built from exactly the keys the engine documents, and
# `mcp` is omitted entirely when there is no tool to point at.
jq -nc --arg mcp "$MCP_FILE" --arg tool "$TOOL" \
  --arg provider "${AMPLIFIER_AGENT_PROVIDER:-}" --arg model "${AMPLIFIER_AGENT_MODEL:-}" '
  {approval: {mode: "yes"}}
  + (if $tool == "" then {} else {mcp: {configPath: $mcp}} end)
  + (if $provider == "" then {} else
      {provider: ({module: $provider}
        + (if $model == "" then {} else {config: {default_model: $model}} end))}
     end)' > "$CONFIG"

ARGS=(run -y --session-id "$SESSION_ID" --cwd "$WS" --config "$CONFIG"
      --output json --display ndjson)
[ -n "${AMPLIFIER_AGENT_MODE:-}" ] && ARGS+=(--mode "$AMPLIFIER_AGENT_MODE")
# `--resume` is a flag over a saved transcript, not an id, so whether we have
# been here is the only thing worth remembering.
[ -f "$STATE/ran" ] && ARGS+=(--resume)

OUT="$(amplifier-agent "${ARGS[@]}" "$(default_prompt "$REQ")" 2>>"$STATE/display.ndjson")"; RC=$?
if [ $RC -ne 0 ] && [ -f "$STATE/ran" ]; then
  echo "resume failed ($RC); starting the session over" >&2
  RETRY=(); for a in "${ARGS[@]}"; do [ "$a" = "--resume" ] && continue; RETRY+=("$a"); done
  OUT="$(amplifier-agent "${RETRY[@]}" --fresh "$(default_prompt "$REQ")" 2>>"$STATE/display.ndjson")"; RC=$?
fi
printf '%s\n' "$OUT" >&2
debug_dump "$WS" "stdout" "$OUT"
touch "$STATE/ran"

[ $RC -ne 0 ] && { failed_result "amplifier-agent exited $RC"; exit 0; }

# Stdout is one envelope line, and the streams are strictly separated, so this
# needs none of the guessing the other wrappers do about where a summary lives.
ERR="$(printf '%s' "$OUT" | jq -r '.error // empty' 2>/dev/null)"
[ -n "$ERR" ] && { failed_result "$(printf '%s' "$ERR" | head -c 300)"; exit 0; }
REPLY="$(printf '%s' "$OUT" | jq -r '.reply // empty' 2>/dev/null)"
SUMMARY="$(printf '%s' "$REPLY" | head -c 400 | tr '\n' ' ')"

# Three channels, best first. The tool is validated and can refuse a bad call;
# the response is the one every assistant has; the prose heuristic is a last
# resort and may only be wrong towards `progressed`, which leaves the work ours
# and the register honest that nothing moved.
if DECLARED="$(declared_outcome "$WS")"; then
  printf '%s' "$DECLARED" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi
if SAID="$(response_outcome "$REPLY")"; then
  printf '%s' "$SAID" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi
jq -nc --arg n "${SUMMARY:-ran and said nothing}" '{outcome:"progressed", note:$n}'
EOF_src_wrapper_amplifieragent
}

src_wrapper_claude() { cat <<'EOF_src_wrapper_claude'
#!/usr/bin/env bash
# Claude Code.
#
# Continuation: **captured**. A run prints its own `session_id` in the JSON
# result, and resuming means handing that back with `--resume`. So the id has to
# be kept somewhere between runs, and the workspace is that somewhere -- the
# runner stores nothing on a wrapper's behalf.
#
# The old runner passed `--no-session-persistence`, which meant every tick met
# the task for the first time. Feedback three days later arrived at an assistant
# with no memory of having done the work.
set -uo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/lib.sh"

REQ="$(cat)"
claude_traces  # its own spans, under the TRACEPARENT the runner set; opt-in
WS="$(printf '%s' "$REQ" | jq -r '.workspace')"
STATE="$WS/.harness/claude"; mkdir -p "$STATE"
SESSION_FILE="$STATE/session"

PROMPT="$(default_prompt "$REQ")"
ARGS=(-p "$PROMPT" --output-format json --permission-mode acceptEdits --max-turns "${CLAUDE_MAX_TURNS:-40}")
[ -n "${CLAUDE_MODEL:-}" ] && ARGS+=(--model "$CLAUDE_MODEL")

# The outcome tool, offered over MCP. An assistant asked to call a tool calls it
# far more reliably than one asked to remember a file on its way out -- and an
# invalid call comes back refused, with a reason, in time for it to fix.
#
# Merged with whatever the operator configured rather than replacing it: this is
# one small server, and clobbering somebody's task tools to add it would be a
# poor trade. `--allowedTools` is not optional when `--strict-mcp-config` is on:
# without it the run reaches the model, discovers it may not call the tool,
# explains that politely, and exits 0 -- which is how every tick came to re-do
# the same nothing before that flag existed.
TOOL="$(install_outcome_tool "$WS" || true)"
MCP="${CLAUDE_MCP_CONFIG:-}"
# `--allowedTools` is an allowlist, so naming the MCP server narrows everything
# else *out*. The first real run delivered twice with "verified by inspection
# since running python was not permitted" -- it could write the file and not run
# it, because Bash was no longer on the list. So the list starts with a working
# set and the MCP server is appended to it.
ALLOWED="${CLAUDE_ALLOWED_TOOLS:-Read,Write,Edit,Glob,Grep,Bash,TodoWrite}"
if [ -n "$TOOL" ]; then
  OURS="$(jq -nc --arg c "$(command -v python3)" --arg a "$TOOL" --arg ws "$WS" \
    '{mcpServers:{harness:{command:$c, args:[$a], env:{HARNESS_WORKSPACE:$ws}}}}')"
  if [ -n "$MCP" ]; then
    MCP="$(jq -sc '.[0] * .[1]' <(printf '%s' "$MCP") <(printf '%s' "$OURS"))"
  else
    MCP="$OURS"
  fi
  ALLOWED="${ALLOWED:+$ALLOWED,}mcp__harness"
fi
[ -n "$MCP" ] && ARGS+=(--mcp-config "$MCP" --strict-mcp-config)
[ -n "$ALLOWED" ] && ARGS+=(--allowedTools "$ALLOWED")

# Resume if we have been here before, and fall back to a fresh session if the id
# is stale. A session that has expired must not become a task that never runs.
if [ -s "$SESSION_FILE" ]; then
  ARGS+=(--resume "$(cat "$SESSION_FILE")")
fi

cd "$WS" || { failed_result "cannot enter $WS"; exit 0; }
# stdout only. The tools separate their streams and this used to merge them with
# `2>&1`, so a diagnostic line landed in the middle of the data: pi prints
# "Warning: No project session found ... creating a new session" on the first run
# of a session, which made the whole JSONL stream unparseable and sent a slice of
# the prompt to the register as the agent's report. Stderr is left to flow to the
# wrapper's own stderr, which the runner already keeps in the run log.
OUT="$(claude "${ARGS[@]}")"; RC=$?
if [ $RC -ne 0 ] && [ -s "$SESSION_FILE" ]; then
  echo "resume failed ($RC); starting a fresh session" >&2
  rm -f "$SESSION_FILE"
  FRESH=(); for a in "${ARGS[@]}"; do [ "$a" = "--resume" ] && break; FRESH+=("$a"); done
  OUT="$(claude "${FRESH[@]}")"; RC=$?
fi
printf '%s\n' "$OUT" >&2
debug_dump "$WS" "stdout" "$OUT"

# `--output-format json` is an *array* of events in current versions and was a
# single object in older ones. Both are handled rather than pinned, because a
# wrapper that breaks on an upgrade of the thing it wraps is a wrapper that will
# be broken the day nobody is looking at it.
envelope() { printf '%s' "$OUT" | jq -c 'if type=="array" then (.[] | select(.type=="result")) else . end' 2>/dev/null | tail -1; }
SID="$(envelope | jq -r '.session_id // empty' 2>/dev/null)"
[ -z "$SID" ] && SID="$(printf '%s' "$OUT" | jq -r 'if type=="array" then (.[]|.session_id?) else .session_id end' 2>/dev/null | grep -v '^null$' | head -1)"
[ -n "$SID" ] && printf '%s' "$SID" > "$SESSION_FILE"

if [ $RC -ne 0 ]; then
  failed_result "claude exited $RC"; exit 0
fi

# The model's own summary, not a slice of its JSON. A report made of two hundred
# arbitrary characters is barely better than silence, and that is what the old
# runner was posting every minute when its `jq` path came up empty.
REPLY="$(envelope | jq -r '.result // empty' 2>/dev/null)"
SUBTYPE="$(envelope | jq -r '.subtype // empty' 2>/dev/null)"
if [ -n "$SUBTYPE" ] && [ "$SUBTYPE" != "success" ]; then
  failed_result "run ended $SUBTYPE: $(envelope | jq -r '.result // .error // empty' | head -c 200)"
  exit 0
fi

# The whole reply for parsing -- the outcome block is at the *end* of it, so a
# truncated copy is exactly the wrong thing to look in. The short form is only
# ever the note.
SUMMARY="$(printf '%s' "$REPLY" | head -c 400)"
[ -z "$SUMMARY" ] && SUMMARY="ran, but said nothing a summary could be made of"

# Three channels, best first. The tool is validated and can refuse a bad call;
# the response is the one every assistant has; the prose heuristic below is a
# last resort. Its own note beats ours, so the summary is kept only when it
# left none.
if DECLARED="$(declared_outcome "$WS")"; then
  printf '%s' "$DECLARED" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi
if SAID="$(response_outcome "$REPLY")"; then
  printf '%s' "$SAID" | jq -c --arg s "$SUMMARY" '.note = (if .note == "" then $s else .note end)'
  exit 0
fi

# It did not say. Read its prose for a blocker rather than reporting progress
# that may not have happened -- a heuristic, and allowed to be wrong only in the
# safe direction: a missed blocker becomes `progressed`, which leaves the work
# ours and leaves the register honest that nothing moved.
if printf '%s' "$SUMMARY" | grep -qiE "need(s)? (a )?(decision|input|clarif)|blocked|cannot proceed|unable to proceed"; then
  jq -nc --arg n "$SUMMARY" '{outcome:"blocked", note:$n, question:$n}'
else
  jq -nc --arg n "$SUMMARY" '{outcome:"progressed", note:$n}'
fi
EOF_src_wrapper_claude
}

src_wrapper_claudecoder() { cat <<'EOF_src_wrapper_claudecoder'
#!/usr/bin/env bash
# Claude Code, set up to write code rather than to answer.
#
# The difference from `claude` is not the model, it is what the assistant is
# given and what it is told:
#
#   - the language tools. `LSP` and `Task` are on the allowlist, so it can ask
#     the language server where a symbol is used instead of grepping for the
#     string and hoping. Coding runs are also allowed more turns, because a real
#     change is read-edit-build-test and each of those is a turn.
#   - the workflow. A coding assistant that does not know its working directory
#     persists will clone the repository again every run, and one that does not
#     know the directory is *its own* will be shy about writing in it. Both are
#     failures of briefing rather than of ability, so this ships the briefing.
#
# Everything else -- how an outcome is reported, how a session resumes -- is the
# same as every other wrapper, which is the point of there being a contract.
set -uo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/lib.sh"

REQ="$(cat)"
claude_traces  # its own spans, under the TRACEPARENT the runner set; opt-in
WS="$(printf '%s' "$REQ" | jq -r '.workspace')"
STATE="$WS/.harness/claude-coder"; mkdir -p "$STATE"
SESSION_FILE="$STATE/session"

# The briefing, written beside the general one on every run so an edit here
# reaches every agent without redeploying anything.
cat > "$WS/CODING.md" <<'BRIEF'
# Working on code here

## This directory is yours, and it persists

You are in a working directory that belongs to **this one piece of work**. It is
still here next time you are asked about the same thing, with whatever you left
in it. So:

- **Look before you fetch.** If the repository you need is already cloned here,
  use it — pull, do not clone again. Re-cloning every run throws away branches,
  build caches and anything uncommitted.
- **Write freely.** This is not a shared checkout and nothing else is using it.
- **Keep scratch work.** Notes, a plan, a failing test you have not fixed yet:
  leave them. Future-you reads them.

If the work needs a repository nobody has cloned yet, clone it here. `git` and a
`GITHUB_TOKEN` are available.

## Use the language server

`LSP` is available and is better than grep for anything structural: where a
symbol is defined, everywhere it is used, what the type is, what the compiler
already thinks is wrong. Reach for it before reading whole files, and read the
diagnostics before deciding you are finished.

## Finish like an engineer

- **Run the tests.** A change you have not run is a claim, and `delivered` is
  supposed to mean more than that.
- **Read the diagnostics** after editing, not before.
- **Do not commit or push unless you were asked to.** If you were: work on a
  branch, never on the default one, and say in your note what you pushed.
- If you cannot build or test — a missing toolchain, no network — that is
  `blocked` with a specific question, not `delivered` with a caveat.

## Scope

Do what was asked and stop. A refactor nobody requested is not a bonus; it is a
larger diff for somebody else to review. If you find something else wrong, say so
in your note rather than fixing it.
BRIEF

PROMPT="$(default_prompt "$REQ")
Read CODING.md in this directory before you start. It describes how this
workspace is used and what finishing means here."

ARGS=(-p "$PROMPT" --output-format json --permission-mode acceptEdits
      --max-turns "${CLAUDE_MAX_TURNS:-80}")
[ -n "${CLAUDE_MODEL:-}" ] && ARGS+=(--model "$CLAUDE_MODEL")

TOOL="$(install_outcome_tool "$WS" || true)"
MCP="${CLAUDE_MCP_CONFIG:-}"
# Wider than the general wrapper's: this one is meant to navigate a codebase and
# build it. `--allowedTools` is an allowlist, so anything absent is refused --
# which is how the first real run came to deliver twice having never been able
# to run the tests it claimed to have checked.
ALLOWED="${CLAUDE_ALLOWED_TOOLS:-Read,Write,Edit,Glob,Grep,Bash,TodoWrite,LSP,Task,WebFetch,WebSearch}"
if [ -n "$TOOL" ]; then
  OURS="$(jq -nc --arg c "$(command -v python3)" --arg a "$TOOL" --arg ws "$WS" \
