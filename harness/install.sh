#!/usr/bin/env bash
# Install a docket runner on this machine.
#
#   curl -fsSL https://raw.githubusercontent.com/payneio/docket/main/harness/install.sh \
#     | bash -s -- --harness claude-code
#   ./install.sh --harness pi --dir ~/bin
#   sudo -u coder bash -lc 'curl … | bash -s -- --harness claude-coder --arm'
#
# --arm also writes ~/agent, the loop a fleetix principal's unit runs, and a
# ~/.config/agent/env for its settings, then restarts the unit. It replaces only
# fleetix's unarmed stub; --force replaces anything, keeping ~/agent.bak.
#
# Writes ONE executable that contains everything: the runner, its library, and
# the wrapper for the assistant you named. It re-executes itself to invoke the
# wrapper, so the subprocess contract is unchanged -- the subprocess is just the
# same file wearing a different hat.
#
# GENERATED by harness/build-installer. Edit the sources, not this.
set -euo pipefail

HARNESS=""
DEST="${HARNESS_DIR:-$HOME/.local/bin}"
NAME=""
ARM=""
FORCE=""

die() { printf 'install: %s\n' "$*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --harness) HARNESS="${2:-}"; shift 2 ;;
    --dir)     DEST="${2:-}"; shift 2 ;;
    --name)    NAME="${2:-}"; shift 2 ;;
    --list)    LIST=1; shift ;;
    --arm)     ARM=1; shift ;;
    --force)   FORCE=1; shift ;;
    -h|--help)
      sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option $1" ;;
  esac
done
src_lib() { cat <<'EOF_src_lib'
# Shared by the runner and by wrappers that want it. Sourced, never executed.

#: Where the sources are, when there are sources. A bundled runner defines
#: `write_outcome_tool` instead and never reads this -- but without a default
#: here, running from a checkout silently had no tool to offer at all, and the
#: only sign was an MCP server that failed to start.
_HARNESS_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd 2>/dev/null)" || _HARNESS_LIB_DIR="."
: "${HARNESS_TOOL_SRC:=$_HARNESS_LIB_DIR/tools/report-outcome}"

: "${DOCKET_URL:=http://127.0.0.1:9006}"
: "${DK_CRED:=$HOME/.docket/credential}"

#: The credential, from the environment or from a file.
#:
#: `DOCKET_API_KEY` first, because a new box is one `export` away from working
#: and a file is a thing to create, own and forget. If it turns out to be a
#: ticket (`dke_`) it is spent for a real credential on first use -- so a single
#: variable either *is* the identity or *buys* it, and nothing has to know which
#: in advance.
docket_credential() {
  local key="${DOCKET_API_KEY:-}"
  if [ -z "$key" ] && [ -s "${DOCKET_CREDENTIAL_FILE:-$HOME/.docket/credential}" ]; then
    key="$(cat "${DOCKET_CREDENTIAL_FILE:-$HOME/.docket/credential}")"
  fi
  case "$key" in
    dke_*) key="$(docket_enrol "$key")" ;;
  esac
  printf '%s' "$key"
}

#: Spend a ticket, keep what comes back. Once, and then never again -- the
#: credential is written where the next run will find it without the ticket.
docket_enrol() {  # <ticket>
  local file out token
  file="${DOCKET_CREDENTIAL_FILE:-$HOME/.docket/credential}"
  if [ -s "$file" ]; then cat "$file"; return; fi
  out="$(curl -s -X POST "$DOCKET_URL/enrol" -H @<(bearer "$1") \
         -H 'Content-Type: application/json' \
         -d "$(jq -nc --arg l "${HARNESS_LABEL:-$(hostname -s)}" '{label:$l}')")"
  token="$(printf '%s' "$out" | jq -r '.token // empty')"
  if [ -z "$token" ]; then
    printf 'could not enrol: %s\n' "$out" >&2
    return 1
  fi
  mkdir -p "$(dirname "$file")" && chmod 700 "$(dirname "$file")"
  ( umask 077; printf '%s' "$token" > "$file" )
  printf 'enrolled as %s\n' "$(printf '%s' "$out" | jq -r .party)" >&2
  printf '%s' "$token"
}

#: An Authorization header, as a file for `curl -H @...`. Never as an argument:
#: argv is world-readable in /proc, so a token passed with `-H "...$KEY"` can be
#: read by every account on the box -- including the other principals the uid is
#: meant to keep it from. `printf` is a builtin, so the token is in no argv at all.
bearer() { printf 'Authorization: Bearer %s\n' "$1"; }

ts() { date -Is; }
log() { printf '%s %s\n' "$(ts)" "$*" >&2; }

#: Which run this is, as W3C Trace Context. One trace per pass, so every move a
#: pass makes -- and any question it opens -- shares a trace id, and the board
#: can show them as one piece of work. One span id per entry handled, so moves
#: on different entries stay distinguishable inside the run.
#:
#: Generated here, never inherited: the loop in `~/agent` lives for weeks, and a
#: `TRACEPARENT` it happened to carry would put every pass into one trace
#: forever. Flags `01` (sampled), so a collector that samples on the parent's
#: decision keeps what docket records.
HARNESS_TRACE_ID=""
HARNESS_SPAN_ID=""
hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }
new_run() {
  HARNESS_TRACE_ID="$(hex 16)"; HARNESS_SPAN_ID="$(hex 8)"
  HARNESS_PASS_SPAN="$HARNESS_SPAN_ID"; HARNESS_PASS_START="$(now_ns)"
}
new_span() { HARNESS_SPAN_ID="$(hex 8)"; }
traceparent() {
  [ -n "$HARNESS_TRACE_ID" ] && printf '00-%s-%s-01' "$HARNESS_TRACE_ID" "$HARNESS_SPAN_ID"
}

#: Spans, for a collector, as OTLP/JSON over plain HTTP -- the standard
#: encoding, sent with the curl and jq this already depends on, because a tracing
#: SDK cannot ride along in a single-file installer. Exported unless the standard
#: switches say not to (`OTEL_SDK_DISABLED=true`, `OTEL_TRACES_EXPORTER=none`),
#: to `OTEL_EXPORTER_OTLP_[TRACES_]ENDPOINT`, default `http://localhost:4318`.
#:
#: Collected through the pass and sent once, at its end, in the background under
#: a short timeout: a collector that is down or wedged must never lengthen a
#: pass. Attributes are an allow-list -- ids, states, outcomes, names. Never a
#: subject label, terms, a note or a question: those are the register's, which
#: scopes who may read them, and a trace store does not.
HARNESS_SPANS=()
HARNESS_PASS_SPAN=""
HARNESS_PASS_START=""
now_ns() { date +%s%N; }
traces_on() {
  [ "${OTEL_SDK_DISABLED:-}" != "true" ] || return 1
  case "${OTEL_TRACES_EXPORTER:-otlp}" in otlp) ;; *) return 1 ;; esac
  # This speaks OTLP over HTTP only; a gRPC endpoint would just refuse it.
  [ "${OTEL_EXPORTER_OTLP_TRACES_PROTOCOL:-${OTEL_EXPORTER_OTLP_PROTOCOL:-}}" != "grpc" ]
}
span() {  # <name> <span-id> <parent-id|""> <start-ns> <end-ns> <ok|error> <attrs-json> [<links-json>]
  traces_on || return 0
  HARNESS_SPANS+=("$(jq -nc --arg n "$1" --arg t "$HARNESS_TRACE_ID" --arg s "$2" --arg p "$3" \
    --arg a "$4" --arg b "$5" --arg st "$6" --argjson at "$7" --argjson l "${8:-[]}" '{
      traceId:$t, spanId:$s, name:$n, kind:1, startTimeUnixNano:$a, endTimeUnixNano:$b,
      status:{code:(if $st=="error" then 2 else 1 end)},
      attributes:[$at|to_entries[]|{key, value:{stringValue:(.value|tostring)}}],
      links:[$l[]|{traceId:.trace_id, spanId:.span_id}]
    } + (if $p=="" then {} else {parentSpanId:$p} end)')")
}
flush_spans() {
  traces_on && [ ${#HARNESS_SPANS[@]} -gt 0 ] || return 0
  local url="${OTEL_EXPORTER_OTLP_TRACES_ENDPOINT:-${OTEL_EXPORTER_OTLP_ENDPOINT:-http://localhost:4318}/v1/traces}"
  local resource="service.name=${OTEL_SERVICE_NAME:-docket-harness},process.owner=$(id -un)${OTEL_RESOURCE_ATTRIBUTES:+,$OTEL_RESOURCE_ATTRIBUTES}"
  printf '%s\n' "${HARNESS_SPANS[@]}" | jq -sc --arg r "$resource" '{resourceSpans:[{
      resource:{attributes:[$r|split(",")[]|select(contains("="))|capture("^(?<k>[^=]+)=(?<v>.*)$")
                            |{key:.k, value:{stringValue:.v}}]},
      scopeSpans:[{scope:{name:"docket-harness"}, spans:.}]}]}' \
    | timeout 5 curl -s -o /dev/null -X POST "$url" -H 'Content-Type: application/json' --data-binary @- \
      >/dev/null 2>&1 &
  HARNESS_SPANS=()
}
#: The latest move on an entry made by somebody else, as a span link: what this
#: work is answering. Present only when docket recorded a span of its own for it.
answering() {  # <entry-json> <me>
  printf '%s' "$1" | jq -c --arg me "$2" \
    '[.moves[] | select(.by != $me and .trace_id != null and .span_id != null)] | last
     | if . == null then [] else [{trace_id, span_id}] end'
}

#: Claude Code emits traces of its own (beta), and files them under the
#: `TRACEPARENT` it is started with when run with `-p`, as the wrappers do. Off
#: unless asked for, because it is a beta and it is the assistant's telemetry,
#: not the harness's. Only traces: no metrics or logs unless already configured.
claude_traces() {
  [ "${HARNESS_ASSISTANT_TRACES:-}" = 1 ] && traces_on || return 0
  export CLAUDE_CODE_ENABLE_TELEMETRY=1 CLAUDE_CODE_ENHANCED_TELEMETRY_BETA=1 OTEL_TRACES_EXPORTER=otlp
  export OTEL_EXPORTER_OTLP_PROTOCOL="${OTEL_EXPORTER_OTLP_PROTOCOL:-http/protobuf}"
  export OTEL_METRICS_EXPORTER="${OTEL_METRICS_EXPORTER:-none}" OTEL_LOGS_EXPORTER="${OTEL_LOGS_EXPORTER:-none}"
}

#: Every call carries the credential; nothing else identifies us. Resolved once
#: per process, because enrolling twice would mint two credentials for one agent.
#: And the run it belongs to, when there is one.
DOCKET_KEY=""
dk() {
  [ -z "$DOCKET_KEY" ] && DOCKET_KEY="$(docket_credential)"
  local tp; tp="$(traceparent)"
  curl -s -H @<(bearer "$DOCKET_KEY") ${tp:+-H "traceparent: $tp"} \
       -H 'Content-Type: application/json' "$@"
}

uri_escape() { printf %s "$1" | jq -sRr @uri; }

#: A directory name for a subject URI. Stable, readable, and collision-free
#: enough for a filesystem: the URI's own characters, with anything a path would
#: object to replaced. Two subjects that differ at all still differ here, because
#: nothing is truncated.
workspace_slug() { printf %s "$1" | tr -c 'a-zA-Z0-9._-' '-' | tr -s '-'; }

#: What a wrapper is told. The entry, the conversation so far, and a directory.
#: Deliberately not: the runner's configuration, the credential, or anything
#: about wild-life -- a wrapper that needed those would be one this contract
#: cannot swap out.
execution_request() {  # <entry-json> <workspace> <me>
  jq -n --argjson e "$1" --arg ws "$2" --arg me "$3" '{
    entry: {
      id: $e.id, subject: $e.subject, subject_label: $e.subject_label,
      terms: $e.terms, state: $e.state, requester: $e.requester,
      delegate: $e.delegate, expected_by: $e.expected_by
    },
    moves: [$e.moves[] | {seq, at, by, move, note}],
    workspace: $ws,
    me: $me
  } + (if $e.answer then {answer: $e.answer} else {} end)'
}

#: A serviceable prompt built from the request, for wrappers with nothing better.
#: Any wrapper is free to ignore this and write its own -- which is the point of
#: the prompt living here rather than in the runner, where it used to be one
#: string that assumed every assistant had the same tools.
default_prompt() {  # <request-json>
  printf '%s' "$1" | jq -r '
    "You have taken on the following, and are accountable for it.\n\n"
    + "  What is owed: " + (.entry.subject_label // .entry.subject) + "\n"
    + (if .entry.terms then "  Specifically:  " + .entry.terms + "\n" else "" end)
    + "  Reference:     " + .entry.subject + "\n"
    + "  Working dir:   " + .workspace + "\n\n"
    + (if (.moves | length) > 1 then
        "The conversation so far:\n"
        + ([.moves[] | "  " + .move + (if .note then " — " + .note else "" end)] | join("\n"))
        + "\n\n" else "" end)
    + (if .answer then
        "You were waiting on an answer to: " + (.answer.question // "your question") + "\n"
        + (if .answer.state == "delivered"
           then "The answer: " + (.answer.reply // "(no note; read the conversation)") + "\n\n"
           else "No answer is coming: the question was " + .answer.state
                + (if .answer.reply then " — " + .answer.reply else "" end) + "\n\n" end)
      else "" end)
    + "Do what you can now, in the working directory. Stop when you reach a\n"
    + "stable point rather than looping. If you need a decision from somebody,\n"
    + "say so plainly instead of guessing."'
}

#: The result, out of whatever the wrapper printed.
#:
#: The whole of stdout first, because `jq` pretty-prints by default and a wrapper
#: that forgets `-c` would otherwise have its result read as a bare `}`. Failing
#: that, the last line, so a wrapper may print freely and answer at the end.
result_of() {
  if printf '%s' "$1" | jq -e '.outcome' >/dev/null 2>&1; then printf '%s' "$1"; return; fi
  printf '%s' "$1" | tail -1
}

#: A well-formed refusal, so a wrapper that dies mid-run still says something the
#: register can hold. Silence is the failure the whole design is arranged against.
failed_result() { jq -nc --arg n "$1" '{outcome:"failed", note:$n}'; }

#: An outcome left by the `report_outcome` tool.
#:
#: The file is the tool's transport, not the assistant's contract -- an MCP
#: server is a subprocess and has no other way to hand an answer to the runner.
#: Assistants are asked for a block in their final response instead, because a
#: filesystem the runner can see is a thing not all of them have and a final
#: response is a thing all of them do.
#:
#: Consumed, not just read. A stale outcome from last week's run reported as this
#: run's would be worse than having none.
declared_outcome() {  # <workspace>
  local f="$1/.harness/outcome.json"
  [ -s "$f" ] || return 1
  if jq -e '.outcome | test("^(delivered|progressed|blocked|declined|failed)$")' "$f" >/dev/null 2>&1; then
    jq -c '{outcome, note: (.note // ""), question: (.question // "")}' "$f"
    rm -f "$f"
    return 0
  fi
  printf 'ignoring an outcome file that is not one: %s\n' "$(head -c 200 "$f")" >&2
  rm -f "$f"
  return 1
}

#: Put the outcome tool where the assistant's config can point at it.
#:
#: Written into the workspace rather than assumed to be beside us, because the
#: installed runner is one file and has no repository behind it. `write_tool` is
#: defined by the bundle; from a checkout the file is simply copied.
install_outcome_tool() {  # <workspace> -> path, or nothing
  local dest="$1/.harness/report-outcome"
  mkdir -p "$1/.harness" || return 1
  if declare -F write_outcome_tool >/dev/null 2>&1; then
    write_outcome_tool "$dest"
  elif [ -f "${HARNESS_TOOL_SRC:-}" ]; then
    cp -f "$HARNESS_TOOL_SRC" "$dest"
  else
    return 1
  fi
  # An unrunnable tool is worse than none: the assistant is offered a server
  # that fails to start, and nothing says why except a status nobody reads.
  chmod +x "$dest" 2>/dev/null || return 1
  [ -s "$dest" ] || return 1
  printf '%s' "$dest"
}

#: Validate and tidy an outcome object, or fail.
#:
#: Shared so that every channel is held to the same shape -- a `blocked` with no
#: question is as useless arriving in a response as it is in a tool call.
normalise_outcome() {  # <json>
  printf '%s' "$1" | jq -ce '
    select(.outcome | type == "string")
    | select(.outcome | test("^(delivered|progressed|blocked|declined|failed)$"))
    | {outcome, note: ((.note // "") | tostring), question: ((.question // "") | tostring)}
    | select(.outcome != "blocked" or .question != "")
  ' 2>/dev/null
}

#: The outcome the assistant stated in its final response.
#:
#: The one channel every assistant has. Not all of them can write a file the
#: runner will ever see -- a hosted agent, a sandboxed one, anything behind a
#: gateway -- but all of them answer, so this is the floor that the tool and the
#: file sit above rather than the other way round.
#:
#: Read as a fenced block tagged `outcome`, and failing that as a bare JSON
#: object on its own line. The **last** one wins, so an assistant that quotes the
#: format earlier while explaining itself is not taken at its example.
response_outcome() {  # <final response text>
  local text="$1" block line
  block="$(printf '%s\n' "$text" | awk '
    /^[[:space:]]*```[[:space:]]*outcome[[:space:]]*$/ { inb=1; buf=""; next }
    inb && /^[[:space:]]*```/                          { inb=0; last=buf; next }
    inb                                                { buf = buf $0 "\n" }
    END { printf "%s", last }')"
  if [ -n "$block" ]; then
    normalise_outcome "$block" && return 0
  fi
  line="$(printf '%s\n' "$text" | grep -oE '\{[^{}]*"outcome"[^{}]*\}' | tail -1)"
  [ -n "$line" ] && normalise_outcome "$line" && return 0
  return 1
}

#: Keep an assistant's raw stdout when HARNESS_DEBUG is set.
#:
#: Every wrapper guesses at an undocumented output shape, and when a guess is
#: wrong the only symptom is a strange note in the register -- by which point the
#: output that would explain it is gone. This keeps it.
debug_dump() {  # <workspace> <name> <text>
  [ -n "${HARNESS_DEBUG:-}" ] || return 0
  mkdir -p "$1/.harness/raw" 2>/dev/null || return 0
  printf '%s' "$3" > "$1/.harness/raw/$2"
  printf 'raw %s kept at %s/.harness/raw/%s\n' "$2" "$1" "$2" >&2
}

#: Block until there is plausibly something to do, then return.
#:
#: `GET /stream` is Server-Sent Events, already filtered server-side to moves on
#: conversations this credential is named on -- so *any* move that arrives is
#: worth a tick, with one exception: our own. The runner posts a move at the end
#: of nearly every pass, and waking on that would be a loop with no sleep in it.
#: The stream's `open` frame says which party we are, so the filter needs no
#: extra call to find out.
#:
#: **It returns on a timeout too, and that is not a fallback.** Staleness is the
#: *absence* of events: nothing will ever be published to say a delegate has gone
#: quiet for three days. So a sweep on our own clock is still required, and this
#: is where it comes from -- the stream turns it from every sixty seconds into
#: every fifteen minutes, which is the whole of what it buys.
#:
#: Returns 0 when it waited properly (event or sweep), 1 when the stream could
#: not be followed at all. A caller that cannot reach the stream must fall back
#: to sleeping, never to stopping.
wait_for_work() {
  local sweep="${HARNESS_SWEEP_SECONDS:-900}" me="" ev="" line data by opened=""
  [ -z "$DOCKET_KEY" ] && DOCKET_KEY="$(docket_credential)"

  exec 3< <(curl -sN --max-time "$sweep" \
              -H @<(bearer "$DOCKET_KEY") \
              -H 'Accept: text/event-stream' "$DOCKET_URL/stream" 2>/dev/null)
  local pid=$!

  while IFS= read -r line <&3; do
    case "$line" in
      "event: "*) ev="${line#event: }" ;;
      ": "*)      ;;                       # heartbeat: still connected, nothing to report
      "data: "*)
        data="${line#data: }"
        if [ "$ev" = "open" ]; then
          me="$(printf '%s' "$data" | jq -r '.party // empty' 2>/dev/null)"
          opened=1
        elif [ "$ev" = "move" ]; then
          by="$(printf '%s' "$data" | jq -r '.by // empty' 2>/dev/null)"
          if [ -n "$by" ] && [ "$by" != "$me" ]; then
            exec 3<&-; kill "$pid" 2>/dev/null
            return 0
          fi
        fi ;;
    esac
  done
  exec 3<&-; kill "$pid" 2>/dev/null
  # Opened and then ended = the sweep timer elapsed, which is a proper wait.
  # Never opened = there is no stream to follow, and the caller must know.
  [ -n "$opened" ] && return 0 || return 1
}
EOF_src_lib
}

src_runner() { cat <<'EOF_src_runner'
#!/usr/bin/env bash
# Turn "it is my turn" into one invocation of a wrapper, and what it returns
# into a move.
#
# This is what is left of fleetix's reference-agent once everything that knew
# about a particular assistant is gone. What it knows: how to ask docket what is
# owed, how to keep a directory, how to run a subprocess, and how to write down
# what happened. It does not know what a wrapper does, what a subject means, or
# what finishing looks like.
#
# What it deliberately no longer does:
#   - accept work before looking at it. Accepting is a promise, and the previous
#     version made it on the assistant's behalf before the assistant had seen
#     anything, which left a refusal unexpressible.
#   - decide that finishing means a row changed in wild-life. That was true of
#     one deployment and became a rule for everybody. Now it is a verifier, and
#     there is usually no verifier.
#   - build the prompt. Different assistants want different prompts; the one
#     that used to live here assumed every assistant had the same MCP tools.
#
# `set -e` is intentionally NOT used: nearly every step here has a considered
# failure path, and an early exit would skip the part that reports it.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=harness/lib.sh
. "$HERE/lib.sh"

: "${HARNESS_WRAPPER:?set HARNESS_WRAPPER to the wrapper to invoke}"
: "${HARNESS_WORKSPACES:=$HOME/workspaces}"
: "${HARNESS_STATE:=$HOME/.harness}"
: "${HARNESS_VERIFIER:=}"
: "${HARNESS_AGENTS_MD:=$HERE/AGENTS.md}"
NAME="$(basename "$HARNESS_WRAPPER")"

# `--wait` blocks until there is plausibly something to do and then exits. It is
# a separate mode rather than a flag on the pass, so the pass stays exactly what
# it was: ask, work, exit. Deliberately before the lock -- waiting is not
# working, and holding the lock while idle would stop the next tick ever running.
if [ "${1:-}" = "--wait" ]; then
  wait_for_work || { log "$NAME cannot follow $DOCKET_URL/stream"; exit 1; }
  exit 0
fi

mkdir -p "$HARNESS_STATE/logs" "$HARNESS_WORKSPACES" || exit 1

# One tick at a time. A run can outlast the interval that started it, and two
# ticks working the same entry would race each other into the same directory.
exec 9>"$HARNESS_STATE/lock"
flock -n 9 || { log "$NAME busy, skipping this tick"; exit 0; }

new_run
# The pass's own span, ended and sent however the pass ends -- including being
# stopped by the loop's `timeout`, which is why TERM becomes an ordinary exit.
end_pass() {
  local rc=$?
  span harness.pass "$HARNESS_PASS_SPAN" "" "$HARNESS_PASS_START" "$(now_ns)" \
    "$([ $rc -eq 0 ] && echo ok || echo error)" "$(jq -nc --arg w "$NAME" '{"harness.wrapper":$w}')"
  flush_spans
}
trap end_pass EXIT
trap 'exit 143' TERM
ME="$(dk "$DOCKET_URL/me" | jq -r '.party // empty')"
if [ -z "$ME" ]; then
  # Never guess. An unreachable register is not an empty one, and doing the work
  # anyway is how an agent ends up acting on something nobody asked it for.
  log "$NAME cannot reach docket at $DOCKET_URL — doing nothing"
  exit 1
fi

open="$(dk "$DOCKET_URL/entries?party=$(uri_escape "$ME")&open_only=true")"
# Mine to answer: I am the delegate, it is my move, and I am not waiting on a
# question I have already asked. `whose_turn` is the register's own rule -- a
# party that has just spoken is waiting, not stalling -- so it is read here
# rather than re-derived, which is how the two came to disagree before.
todo="$(printf '%s' "$open" | jq -c '[.[]
  | select(.your_role == "delegate")
  | select(.whose_turn == "delegate")
  | select(.is_blocked | not)
  | select(.state == "offered" or .state == "accepted")]')"

move() {  # <entry-id> <move> [note] [extra-json]
  local extra body
  extra="${4:-}"; [ -z "$extra" ] && extra='{}'
  body="$(jq -n --arg m "$2" --arg n "${3:-}" --argjson x "$extra" \
          '{move:$m} + (if $n=="" then {} else {note:$n} end) + $x')"
  dk -o /dev/null -w '%{http_code}' -X POST "$DOCKET_URL/entries/$1/moves" -d "$body"
}

# Work held up by a question I asked, where the question has moved since I last
# spoke on the work. The register cannot hand these back by itself: the last
# move on the held entry is my own `update`, so by its rule it is the other
# side's turn, and settling the question changes nothing about that. Left
# alone, the answer arrives and nobody acts on it -- the question sits at
# `delivered` and the work sits waiting on a reply it already has.
#
#   delivered            -> it is my question, so I settle it, and take the
#                           answer back to the work.
#   declined, withdrawn  -> no answer is coming; go back to the work and say so,
#                           so the assistant can decide what that means.
#   anything else        -> still being answered; keep waiting.
resumed='[]'
while read -r held; do
  [ -z "$held" ] && continue
  hid="$(printf '%s' "$held" | jq -r '.id')"
  qid="$(printf '%s' "$held" | jq -r '.blocked_on')"
  q="$(dk "$DOCKET_URL/entries/$qid")"
  qstate="$(printf '%s' "$q" | jq -r '.state // empty')"
  # Only if the question moved after I last did: otherwise this is an answer I
  # have already been given, and resuming again would loop on it.
  newer="$(jq -n --argjson h "$held" --argjson q "$q" \
    '($q.moves | last | .at) > ($h.moves | last | .at)')"
  [ "$newer" = "true" ] || continue
  case "$qstate" in
    delivered)
      # Mine to settle only if I asked it. Work can wait on an entry somebody
      # else opened; then the answer is still news, but closing it is theirs.
      if [ "$(printf '%s' "$q" | jq -r '.requester')" = "$ME" ]; then
        code="$(move "$qid" settle "answered; back to ${hid:0:8}")"
        [ "$code" = "200" ] || { log "$NAME could not settle ${qid:0:8} ($code)"; continue; }
        log "$NAME ${hid:0:8} answered; settled ${qid:0:8}"
      else
        log "$NAME ${hid:0:8} answered by ${qid:0:8}, which is not mine to settle"
      fi ;;
    declined|withdrawn)
      log "$NAME ${hid:0:8} question ${qid:0:8} was $qstate" ;;
    *) continue ;;
  esac
  answer="$(printf '%s' "$q" | jq -c --arg st "$qstate" '{
    question: .terms, state: $st,
    reply: ([.moves[] | select(.move != "settle") | .note // empty] | last)}')"
  resumed="$(jq -c --argjson r "$resumed" --argjson h "$held" --argjson a "$answer" \
    -n '$r + [$h + {answer: $a}]')"
done < <(printf '%s' "$open" | jq -c '.[]
  | select(.your_role == "delegate")
  | select(.state == "offered" or .state == "accepted")
  | select(.blocked_on != null)
  | select((.whose_turn == "delegate" and (.is_blocked | not)) | not)')
todo="$(jq -c -n --argjson t "$todo" --argjson r "$resumed" '$t + $r')"

count="$(printf '%s' "$todo" | jq 'length')"
[ "$count" = "0" ] && { log "$NAME nothing to answer"; exit 0; }
log "$NAME has $count to answer"

#: Ask the requester something, and record that we are waiting on the answer.
#: A question is an entry in the other direction -- the same loop, and it stays
#: outstanding until somebody answers it.
ask() {  # <entry-json> <question> -> question entry id
  local subject requester label
  subject="$(printf '%s' "$1" | jq -r '.subject')"
  requester="$(printf '%s' "$1" | jq -r '.requester')"
  label="$(printf '%s' "$1" | jq -r '.subject_label // empty')"
  dk -X POST "$DOCKET_URL/entries" -d "$(jq -n \
      --arg s "$subject" --arg d "$requester" --arg t "$2" --arg l "$label" \
      '{subject:$s, delegate:$d, terms:$t}
       + (if $l=="" then {} else {subject_label:$l} end)')" \
    | jq -r '.id // empty'
}

while read -r entry; do
  [ -z "$entry" ] && continue
  eid="$(printf '%s' "$entry" | jq -r '.id')"
  new_span  # same run, its own span: this entry's moves, and the wrapper's context
  entry_span="$HARNESS_SPAN_ID"; entry_start="$(now_ns)"
  links="$(answering "$entry" "$ME")"
  subject="$(printf '%s' "$entry" | jq -r '.subject')"
  state="$(printf '%s' "$entry" | jq -r '.state')"

  ws="$HARNESS_WORKSPACES/$(workspace_slug "$subject")"
  mkdir -p "$ws/.harness" || { log "$NAME cannot make $ws"; continue; }

  # The instructions go in every workspace, refreshed each run so an edit to
  # them reaches every agent without anybody redeploying anything. They are how
  # an assistant knows to declare its outcome instead of being guessed at, and
  # `CLAUDE.md` is a copy rather than a symlink because not every tool follows
  # one out of a directory it was told to work in.
  if declare -F write_agents_md >/dev/null 2>&1; then
    write_agents_md "$ws/AGENTS.md"          # bundled: carried inside this file
    cp -f "$ws/AGENTS.md" "$ws/CLAUDE.md" 2>/dev/null
  elif [ -n "${HARNESS_AGENTS_MD:-}" ] && [ -f "$HARNESS_AGENTS_MD" ]; then
    cp -f "$HARNESS_AGENTS_MD" "$ws/AGENTS.md" 2>/dev/null
    cp -f "$HARNESS_AGENTS_MD" "$ws/CLAUDE.md" 2>/dev/null
  fi
  # Never carry an outcome across runs: the wrapper consumes it, but a wrapper
  # that died before reading one would leave it to be read as this run's answer.
  rm -f "$ws/.harness/outcome.json"

  request="$(execution_request "$entry" "$ws" "$ME")"
  runlog="$HARNESS_STATE/logs/$(date +%Y%m%d-%H%M%S)-${eid:0:8}.log"

  log "$NAME -> $NAME wrapper for ${eid:0:8} ($state) in $ws"
  # The wrapper is handed the run as the OTel environment carrier, so an
  # assistant that emits traces of its own (Claude Code, with telemetry on)
  # files them under this entry. Context only: nothing about where to send them.
  wrapper_span="$(hex 8)"; wrapper_start="$(now_ns)"
  out="$(printf '%s' "$request" \
         | TRACEPARENT="00-$HARNESS_TRACE_ID-$wrapper_span-01" HARNESS_ROLE=wrapper \
           "$HARNESS_WRAPPER" 2>>"$runlog")"
  rc=$?
  span harness.wrapper "$wrapper_span" "$entry_span" "$wrapper_start" "$(now_ns)" \
    "$([ $rc -eq 0 ] && echo ok || echo error)" \
    "$(jq -nc --arg w "$NAME" --arg e "$eid" --arg rc "$rc" \
       '{"harness.wrapper":$w, "docket.entry.id":$e, "process.exit.code":$rc}')"
  result="$(result_of "$out")"
  # A wrapper that died, or printed something that is not a result, still has to
  # produce one. What must not happen is nothing: a run that changes the register
  # in no way and tells only a log file is the failure a shared record exists to
  # make visible.
  if [ $rc -ne 0 ] || ! printf '%s' "$result" | jq -e '.outcome' >/dev/null 2>&1; then
    tailed="$(tail -c 200 "$runlog" 2>/dev/null | tr -d '\000' | tr '\n' ' ')"
    result="$(failed_result "wrapper exited $rc: ${tailed:-no output}")"
  fi

  outcome="$(printf '%s' "$result" | jq -r '.outcome')"
  note="$(printf '%s' "$result" | jq -r '.note // empty' | head -c 400)"
  question="$(printf '%s' "$result" | jq -r '.question // empty')"

  # A claim of completion is checked, when there is anything to check it with.
  if [ "$outcome" = "delivered" ] && [ -n "$HARNESS_VERIFIER" ]; then
    if ! why="$(printf '%s' "$request" | "$HARNESS_VERIFIER" 2>&1)"; then
      log "$NAME ${eid:0:8} claimed delivered; verifier disagreed"
      outcome="progressed"
      note="said it was finished; ${why:-the verifier disagreed}"
    fi
  fi

  # Accepting is a promise, so it is made here and only because the wrapper
  # chose to work -- never in advance of it looking.
  if [ "$state" = "offered" ] && [ "$outcome" != "declined" ] && [ "$outcome" != "failed" ]; then
    move "$eid" accept "picked up by $NAME" >/dev/null
  fi

  case "$outcome" in
    declined)
      move "$eid" decline "${note:-declined}" >/dev/null
      log "$NAME declined ${eid:0:8}" ;;
    delivered)
      move "$eid" deliver "${note:-delivered}" >/dev/null
      log "$NAME delivered ${eid:0:8}" ;;
    blocked)
      qid=""
      [ -n "$question" ] && qid="$(ask "$entry" "$question")"
      if [ -n "$qid" ]; then
        move "$eid" update "${note:-blocked}" "$(jq -n --arg b "$qid" '{blocked_on:$b}')" >/dev/null
        log "$NAME ${eid:0:8} blocked; asked the requester"
      else
        # Say it anyway. A blocker recorded badly beats one recorded nowhere.
        move "$eid" update "${note:-blocked}${question:+ — needs: $question}" >/dev/null
        log "$NAME ${eid:0:8} blocked; no question opened"
      fi ;;
    progressed|failed|*)
      move "$eid" update "${note:-$outcome}" >/dev/null
      log "$NAME ${eid:0:8} $outcome — left $state, reported" ;;
  esac
  span harness.entry "$entry_span" "$HARNESS_PASS_SPAN" "$entry_start" "$(now_ns)" \
    "$([ "$outcome" = failed ] && echo error || echo ok)" \
    "$(jq -nc --arg e "$eid" --arg s "$state" --arg o "$outcome" \
       '{"docket.entry.id":$e, "docket.entry.state":$s, "harness.outcome":$o}')" "$links"
done < <(printf '%s' "$todo" | jq -c '.[]')

log "$NAME done"
EOF_src_runner
}

src_agents() { cat <<'EOF_src_agents'
# Working here

This directory belongs to one piece of work. Something was offered to you, you
took it on, and this is where you do it. The directory persists: if you are
asked about this again next week, you will be back here with whatever you left.

**You do not need to know anything about the register that sent you.** You will
not be asked to poll it, read it, or report to it. Something else does that, and
it does it from what you say below.

## Say what happened before you stop

If you have a `report_outcome` tool, call it. Otherwise **end your final
response** with a fenced block, and nothing after it:

````
```outcome
{"outcome": "delivered", "note": "One line. This is what a person reads later."}
```
````

`outcome` is one of:

| | when |
|---|---|
| `delivered` | you believe the thing that was asked for is done |
| `progressed` | you did some of it and it is not finished |
| `blocked` | you cannot go further without an answer from somebody |
| `declined` | this is not yours to do, or you should not be the one doing it |
| `failed` | you could not work — a broken tool, a missing dependency |

When you are `blocked`, the question is required:

````
```outcome
{"outcome": "blocked",
 "note": "Cannot pick between two schemas without knowing the retention rule.",
 "question": "Should old rows be deleted or archived after 90 days?"}
```
````

That question is **opened as a real request to the person who asked you**, and
stays outstanding until they answer it. It is not a note in a log. So ask it the
way you would ask a colleague: one specific thing you need, not a summary of
your confusion.

## Why this matters more than it looks

Without it, whatever ran you has to guess your outcome by reading your prose for
words like "blocked". That works until it doesn't, and when it fails it fails
silently in the expensive direction — work recorded as progressing while it is
stuck, or as finished while it is not.

Two things follow:

- **`declined` is a real answer and you are allowed to give it.** If this was
  offered to you wrongly, say so. Refusing is not failing. What must not happen
  is that you attempt something out of scope because refusing was not an option
  you were offered — the whole arrangement exists so that a refusal is sayable.

- **Do not report progress you have not made.** Saying `progressed` every run
  while nothing changes looks like attention and is worse than silence, because
  it hides how long the work has actually been stuck. If you did nothing, say
  what stopped you.

If you say it more than once, the last one counts — so if you sketch the format
while thinking aloud, put the real answer at the end.

## Do not

- Poll or write to any task system yourself. You will duplicate what is already
  being recorded, and the two will disagree.
- Loop. Reach a stable point and stop. If you need something, ask for it and
  stop; you will be run again when there is an answer.
- Work outside this directory unless what was asked plainly requires it.
EOF_src_agents
}

src_tool() { cat <<'EOF_src_tool'
#!/usr/bin/env python3
"""One tool, over MCP: say what happened.

The assistants that matter here all speak tool calls, and an assistant asked to
call a tool calls it far more reliably than one asked to remember a file on its
way out. So this is the front door.

**It is still the file underneath.** `report_outcome` writes
`<workspace>/.harness/outcome.json`, which is what the wrapper reads, and that
is deliberate rather than lazy:

- an assistant that reports and then dies has still reported;
- the wrapper reads one thing however the answer arrived, so `declared_outcome`
  stays a single function rather than one per transport;
- an assistant with no tools, or one whose tool mechanism nobody has wired yet,
  works by writing the file itself and nothing downstream can tell.

**It is deliberately not a docket client.** It cannot read the register, take on
work, or post updates. The runner speaks docket; giving the assistant its own
client would put the control loop back inside the agent, hand it the credential
it currently never sees, and re-open the door to reporting nothing usefully
every minute.

Stdlib only, JSON-RPC over stdio, so it can be written into a workspace by a
single-file runner that has no package manager behind it.

    HARNESS_WORKSPACE=/path/to/workspace report-outcome
"""

import json
import os
import pathlib
import sys

OUTCOMES = ("delivered", "progressed", "blocked", "declined", "failed")

TOOL = {
    "name": "report_outcome",
    "description": (
        "Record what happened with the work you took on. Call this before you "
        "stop. Calling it again replaces what you said earlier, so the last "
        "call is the answer."
    ),
    "inputSchema": {
        "type": "object",
        "properties": {
            "outcome": {
                "type": "string",
                "enum": list(OUTCOMES),
                "description": (
                    "delivered: you believe what was asked for is done. "
                    "progressed: you did some of it and it is not finished. "
                    "blocked: you cannot go further without an answer. "
                    "declined: this is not yours to do — a real answer, not a "
                    "failure. failed: you could not work at all."
                ),
            },
            "note": {
                "type": "string",
                "description": "One line. A person reads this later.",
            },
            "question": {
                "type": "string",
                "description": (
                    "Only when blocked. Opened as a real request to the person "
                    "who asked you, and it stays outstanding until they answer. "
                    "Ask one specific thing, not a summary of your confusion."
                ),
            },
        },
        "required": ["outcome", "note"],
    },
}


def outcome_path() -> pathlib.Path:
    ws = pathlib.Path(os.environ.get("HARNESS_WORKSPACE", "."))
    d = ws / ".harness"
    d.mkdir(parents=True, exist_ok=True)
    return d / "outcome.json"


def record(args: dict) -> str:
    outcome = args.get("outcome")
    if outcome not in OUTCOMES:
        # Told, not silently corrected: an assistant that gets a refusal can fix
        # it in the same turn, which is the whole advantage of a tool over a file
        # nobody reads back.
        raise ValueError(f"outcome must be one of {', '.join(OUTCOMES)}; got {outcome!r}")
    note = (args.get("note") or "").strip()
    if not note:
        raise ValueError("note is required — one line that a person can read later")
    body = {"outcome": outcome, "note": note}
    if args.get("question"):
        body["question"] = args["question"].strip()
    if outcome == "blocked" and "question" not in body:
        raise ValueError("blocked needs a question: what do you need answered?")
    outcome_path().write_text(json.dumps(body))
    if outcome == "blocked":
        return f"Recorded: blocked. Your question will be put to them: {body['question']}"
    return f"Recorded: {outcome}. You can stop now."


def reply(rid, result=None, error=None) -> None:
    msg = {"jsonrpc": "2.0", "id": rid}
    msg["error" if error else "result"] = error if error else result
    sys.stdout.write(json.dumps(msg) + "\n")
    sys.stdout.flush()


def main() -> None:
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
        except json.JSONDecodeError:
            continue
        method, rid = req.get("method"), req.get("id")
        # Notifications carry no id and must not be answered.
        if rid is None:
            continue

        if method == "initialize":
            # Echo the client's protocol version back. These assistants do not
            # agree on which revision they speak, and refusing the ones that ask
            # for a version this file has never heard of would be a way of
            # supporting only whichever was current the day it was written.
            asked = (req.get("params") or {}).get("protocolVersion") or "2025-06-18"
            reply(rid, {
                "protocolVersion": asked,
                "capabilities": {"tools": {}},
                "serverInfo": {"name": "docket-harness", "version": "1"},
            })
        elif method == "tools/list":
            reply(rid, {"tools": [TOOL]})
        elif method == "tools/call":
            params = req.get("params") or {}
            if params.get("name") != TOOL["name"]:
                reply(rid, error={"code": -32602, "message": f"no tool {params.get('name')!r}"})
                continue
            try:
                text = record(params.get("arguments") or {})
            except ValueError as exc:
                reply(rid, {"content": [{"type": "text", "text": str(exc)}], "isError": True})
            else:
                reply(rid, {"content": [{"type": "text", "text": text}]})
        elif method == "ping":
            reply(rid, {})
        else:
            reply(rid, error={"code": -32601, "message": f"no method {method!r}"})


if __name__ == "__main__":
    main()
EOF_src_tool
}

