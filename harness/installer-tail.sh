
# Aliases, because the assistants are known by more than one name and being told
# "unknown harness: claude-code" when you asked for the thing you have installed
# is a poor welcome.
case "$HARNESS" in
  claude|claude-code|claudecode) HARNESS=claude ;;
  pi)                            HARNESS=pi ;;
  opencode|open-code)            HARNESS=opencode ;;
  amplifier|amplifier-agent)     HARNESS=amplifier ;;
esac

AVAILABLE="$(declare -F | sed -n 's/^declare -f src_wrapper_//p' | sort | tr '\n' ' ')"
if [ -n "${LIST:-}" ]; then
  printf 'harnesses: %s\n' "$AVAILABLE"; exit 0
fi
[ -n "$HARNESS" ] || die "which assistant? --harness <${AVAILABLE// /|}>"
declare -F "src_wrapper_$HARNESS" >/dev/null || die "no harness '$HARNESS'; have: $AVAILABLE"

command -v "$HARNESS" >/dev/null 2>&1 \
  || printf 'install: note — %s is not on PATH yet; the runner will need it\n' "$HARNESS" >&2

: "${NAME:=docket-$HARNESS}"
mkdir -p "$DEST" || die "cannot create $DEST"
OUT="$DEST/$NAME"

# The bundle. `. lib.sh` lines go, because the library is already above them;
# everything else is verbatim, so what runs here is what was tested there.
strip_source() { grep -v '^\. "\$(cd .*lib\.sh"$' | grep -v '^# shellcheck source=harness/lib.sh$' | grep -v '^\. "\$HERE/lib\.sh"$'; }

{
  printf '#!/usr/bin/env bash\n'
  printf '# docket runner for %s. Generated by install.sh; edit nothing here.\n' "$HARNESS"
  printf '#\n'
  printf '#   DOCKET_URL=https://docket.example DOCKET_API_KEY=dk_… %s\n' "$NAME"
  printf '#\n'
  printf '# DOCKET_API_KEY may be a credential (dk_) or a single-use ticket (dke_),\n'
  printf '# which is spent once and replaced by the credential it buys.\n'
  printf 'set -uo pipefail\n\n'

  printf 'HARNESS_AGENTS_MD_INLINE=1\n'
  printf 'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"\n\n'

  printf '# ---- library ----\n'; src_lib | strip_source

  printf '\n# ---- the instructions handed to the assistant ----\n'
  printf 'write_agents_md() {\n  cat > "$1" <<'"'"'EOF_AGENTS'"'"'\n'
  src_agents
  printf 'EOF_AGENTS\n}\n'

  printf '\n# ---- wrapper: %s ----\n' "$HARNESS"
  printf 'wrapper_main() {\n'
  "src_wrapper_$HARNESS" | strip_source | sed 's/^/  /'
  printf '\n}\n'
  printf 'if [ "${HARNESS_ROLE:-}" = "wrapper" ]; then wrapper_main; exit $?; fi\n'

  printf '\n# ---- runner ----\n'
  printf 'HARNESS_WRAPPER="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/%s"\n' "$NAME"
  printf 'export HARNESS_WRAPPER\n'
  src_runner | strip_source
} > "$OUT"
chmod +x "$OUT"

printf 'installed %s\n' "$OUT"
case ":$PATH:" in
  *":$DEST:"*) ;;
  *) printf 'note: %s is not on your PATH\n' "$DEST" >&2 ;;
esac
printf '\nnext:\n  export DOCKET_URL=https://docket.example\n'
printf '  export DOCKET_API_KEY=dke_…      # a ticket from /board/access\n'
printf '  %s\n' "$NAME"
